  fun preview(dark: Boolean) =
    if (tones.isEmpty()) Color(0xFF9CD6C5) else Color(tones[if (dark) 1 else 0])

  fun applyTo(base: ColorScheme, dark: Boolean): ColorScheme {
    if (tones.isEmpty()) return base
    val p = Color(tones[if (dark) 1 else 0])
    val s = Color(tones[if (dark) 3 else 2])
    val t = Color(tones[if (dark) 5 else 4])
    val bg = Color(tones[if (dark) 7 else 6])
    val pc = lerp(bg, p, if (dark) .24f else .20f)
    val sc = lerp(bg, s, if (dark) .24f else .20f)
    val tc = lerp(bg, t, if (dark) .24f else .20f)
    return base.copy(
      primary = p,
      onPrimary = p.readableInk(),
      primaryContainer = pc,
      onPrimaryContainer = pc.readableInk(),
      secondary = s,
      onSecondary = s.readableInk(),
      secondaryContainer = sc,
      onSecondaryContainer = sc.readableInk(),
      tertiary = t,
      onTertiary = t.readableInk(),
      tertiaryContainer = tc,
      onTertiaryContainer = tc.readableInk(),
      background = bg,
      onBackground = bg.readableInk(),
      surface = bg,
      onSurface = bg.readableInk(),
      surfaceVariant = lerp(bg, p, .12f),
      onSurfaceVariant = lerp(bg.readableInk(), bg, .20f),
      outline = lerp(bg, bg.readableInk(), .5f),
      outlineVariant = lerp(bg, p, .24f),
      surfaceContainerLowest = bg,
      surfaceContainerLow = lerp(bg, p, .03f),
      surfaceContainer = lerp(bg, p, .06f),
      surfaceContainerHigh = lerp(bg, p, .09f),
      surfaceContainerHighest = lerp(bg, p, .12f),
      surfaceDim = lerp(bg, Color.Black, .04f),
      surfaceBright = lerp(bg, bg.readableInk(), .06f),
      inverseSurface = bg.readableInk(),
      inverseOnSurface = bg,
      inversePrimary = if (dark) Color(tones[0]) else Color(tones[1]),
    )
  }
}

internal fun Color.readableInk(): Color =
  if ((luminance() + .05f) / .05f >= 1.05f / (luminance() + .05f)) Color.Black else Color.White
