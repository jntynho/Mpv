#!/usr/bin/env python3
"""Convert the selected official Iconsax SVGs into Android/Compose shared vectors.

Usage: python3 scripts/generate-iconsax.py /path/to/Svg.zip
The official archive stays outside the repository. No Flutter/font dependency is used.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = "b855b89705738f2ee24d98a24a9dba8d1784837fb149c334e095853591141285"
NAMESPACE = 'http://schemas.android.com/apk/res/android'
ET.register_namespace('android', NAMESPACE)
def a(name): return '{' + NAMESPACE + '}' + name
def normalized(s): return re.sub(r'(?<![0-9])\.(?=\d)', '0.', s)
selection = json.loads((ROOT / 'scripts/iconsax-selection.json').read_text())
archive = Path(sys.argv[1])
assert hashlib.sha256(archive.read_bytes()).hexdigest() == SOURCE_SHA256, 'Unexpected official archive'
z = zipfile.ZipFile(archive)
res = ROOT / 'app/src/main/res/drawable'
icons = ROOT / 'app/src/main/java/live/mehiz/mpvkt/ui/icons'
mirror_keys = {'ArrowBack', 'FormatAlignLeft', 'FormatAlignRight'}
def vector(style, name, mirrored=False):
    source = ET.fromstring(z.read(f'Svg/All/{style}/{name}.svg'))
    assert source.attrib['viewBox'] == '0 0 24 24'
    root = ET.Element('vector', {a('width'): '24dp', a('height'): '24dp', a('viewportWidth'): '24', a('viewportHeight'): '24'})
    if mirrored: root.set(a('autoMirrored'), 'true')
    for path in source:
        assert path.tag.rsplit('}', 1)[-1] == 'path', (style, name, path.tag)
        assert set(path.attrib) <= {'d', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'stroke-miterlimit'}, (style, name, path.attrib)
        attrs = {a('pathData'): normalized(path.attrib['d']), a('fillColor'): '#FF000000' if path.get('fill', source.get('fill', 'black')) != 'none' else '#00000000'}
        for old, new in [('stroke','strokeColor'), ('stroke-width','strokeWidth'), ('stroke-linecap','strokeLineCap'), ('stroke-linejoin','strokeLineJoin'), ('stroke-miterlimit','strokeMiterLimit')]:
            if old in path.attrib: attrs[a(new)] = '#FF000000' if old == 'stroke' else normalized(path.attrib[old])
        if 'stroke' in path.attrib and 'stroke-width' not in path.attrib:
            attrs[a('strokeWidth')] = '1'  # SVG default; Android vectors default to zero.
        ET.SubElement(root, 'path', attrs)
    ET.indent(root, space='  ')
    return ET.tostring(root, encoding='unicode') + '\n'
entries=[]; manifest=[]
for key, mapping in selection.items():
    names = {style: mapping if isinstance(mapping, str) else mapping[style] for style in ['outline', 'broken']}
    refs=[]
    for style, name in names.items():
        ref=f'iconsax_{style}_{name.replace("-", "_")}'
        data=vector(style,name)
        (res/(ref+'.xml')).write_text(data)
        refs.append('R.drawable.'+ref)
        manifest.append({'key':key,'style':style,'source':f'Svg/All/{style}/{name}.svg','resource':ref,'sha256':hashlib.sha256(data.encode()).hexdigest()})
    if key in mirror_keys:
        for style,name in names.items():
            ref=f'iconsax_{style}_{name.replace("-", "_")}_rtl'
            (res/(ref+'.xml')).write_text(vector(style,name,True))
            refs.append('R.drawable.'+ref)
    entries.append(f'  {key}('+', '.join(refs)+')')
header='''// Generated by scripts/generate-iconsax.py from selected official Iconsax artwork.
package live.mehiz.mpvkt.ui.icons

import androidx.annotation.DrawableRes
import live.mehiz.mpvkt.R

internal enum class IconKey(
  @DrawableRes private val outline: Int,
  @DrawableRes private val broken: Int,
  @DrawableRes private val outlineRtl: Int = outline,
  @DrawableRes private val brokenRtl: Int = broken,
) {
'''
footer=''';

  @DrawableRes
  fun drawable(style: IconStyle, mirrored: Boolean = false): Int = when (style) {
    IconStyle.Outline -> if (mirrored) outlineRtl else outline
    IconStyle.Broken -> if (mirrored) brokenRtl else broken
  }
}
'''
(icons/'IconCatalog.kt').write_text(header+',\n'.join(entries)+footer)
api='''// Generated semantic icon aliases; all styles share the same resource catalogue.
package live.mehiz.mpvkt.ui.icons

import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.vector.ImageVector

'''
for key in selection:
    api+=f'val IconScope.{key}: ImageVector\n  @Composable get() = appIcon(IconKey.{key}, mirrored)\n\n'
(icons/'IconsaxIcons.kt').write_text(api)
(ROOT/'third_party/iconsax/selection.json').write_text(json.dumps({'archiveSha256':SOURCE_SHA256,'icons':manifest},indent=2)+'\n')
print(f'{len(selection)} semantic keys, {len(set(x["resource"] for x in manifest))} shared resources, 6 RTL variants')
